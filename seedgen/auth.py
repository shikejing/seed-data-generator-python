"""Authentication and authorization for definition access.

Authentication model (deliberately simple and self-contained): callers
present an opaque bearer token; tokens are mapped to principals through a
registry supplied at construction time (the default ships a couple of demo
users).  The token store is configuration, not entropy: it never feeds
generated data.

Authorization: a definition can be read or regenerated by its creator, by a
principal holding one of the authorized roles recorded on the definition, or
by an ``admin``.  Denials always carry a machine-distinguishable ``reason``:

* ``missing_credentials``   -- no/invalid token
* ``not_creator_or_owner``  -- authenticated but not on the ACL
* ``definition_required``   -- operation needs a definition that was absent
"""

from __future__ import annotations

import dataclasses

from .errors import ForbiddenError, UnauthorizedError


@dataclasses.dataclass(frozen=True)
class Principal:
    user_id: str
    roles: tuple[str, ...] = ()

    def has_role(self, role: str) -> bool:
        return role in self.roles


# Demo token directory; production deployments inject their own mapping.
DEFAULT_TOKENS: dict[str, Principal] = {
    "token-alice": Principal("alice", ("generator",)),
    "token-bob": Principal("bob", ("generator",)),
    "token-admin": Principal("admin", ("admin",)),
}


class Authorizer:
    ADMIN_ROLE = "admin"
    READER_ROLE = "reader"
    GENERATOR_ROLE = "generator"

    def __init__(self, tokens: dict[str, Principal] | None = None):
        self._tokens = dict(tokens if tokens is not None else DEFAULT_TOKENS)

    def principal_from_token(self, token: str | None) -> Principal:
        if not token or not isinstance(token, str):
            raise UnauthorizedError("missing bearer token")
        principal = self._tokens.get(token)
        if principal is None:
            raise UnauthorizedError("invalid bearer token")
        return principal

    def _owners(self, definition) -> set[str]:
        return {definition.created_by}

    def can_read(self, principal: Principal, definition) -> bool:
        if principal.has_role(self.ADMIN_ROLE):
            return True
        if principal.user_id in self._owners(definition):
            return True
        shared = getattr(definition, "shared_with", ()) or ()
        if f"user:{principal.user_id}" in shared:
            return True
        return any(f"role:{r}" in shared for r in principal.roles)

    def require_read(self, principal: Principal, definition) -> None:
        if definition is None:
            raise ForbiddenError("definition required for authorization",
                                 reason="definition_required")
        if not self.can_read(principal, definition):
            raise ForbiddenError(
                f"{principal.user_id!r} may not read this definition",
                reason="not_creator_or_owner",
            )

    def require_generate(self, principal: Principal, definition=None) -> None:
        if definition is None:
            if not (principal.has_role(self.ADMIN_ROLE)
                    or principal.has_role(self.GENERATOR_ROLE)):
                raise ForbiddenError("generation requires the generator role",
                                     reason="generator_role_required")
            return
        # Regenerating an existing definition implies reading it.
        self.require_read(principal, definition)
