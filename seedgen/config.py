"""Runtime configuration.

Configuration never influences generated bytes: data is determined solely by
the definition content and its pinned algorithm version + seed.  These
settings control operational concerns only (where files live, page caps,
default timeout).
"""

from __future__ import annotations

import os
from dataclasses import dataclass

from . import versions


@dataclass(frozen=True)
class Settings:
    data_dir: str = "./data"
    default_page_size: int = 100
    max_page_size: int = 10_000
    default_algorithm_version: str = versions.DEFAULT_VERSION
    generation_timeout_seconds: float = 30.0


def _env_int(name: str, default: int) -> int:
    raw = os.environ.get(name)
    if raw is None or raw == "":
        return default
    try:
        return int(raw)
    except ValueError:
        return default


def _env_float(name: str, default: float) -> float:
    raw = os.environ.get(name)
    if raw is None or raw == "":
        return default
    try:
        return float(raw)
    except ValueError:
        return default


def load_settings() -> Settings:
    return Settings(
        data_dir=os.environ.get("SEEDGEN_DATA_DIR", "./data"),
        default_page_size=_env_int("SEEDGEN_DEFAULT_PAGE_SIZE", 100),
        max_page_size=_env_int("SEEDGEN_MAX_PAGE_SIZE", 10_000),
        default_algorithm_version=os.environ.get(
            "SEEDGEN_DEFAULT_ALGORITHM_VERSION", versions.DEFAULT_VERSION),
        generation_timeout_seconds=_env_float(
            "SEEDGEN_GENERATION_TIMEOUT_SECONDS", 30.0),
    )
